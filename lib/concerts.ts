export function concertEnd(concert: Concert): string {
  return concert.end ?? concert.start
}

export function isCurrent(concert: Concert, today = '2026-10-08'): boolean {
  return concertEnd(concert) >= today
}

export function concertsFor(options: { ciudad?: string; tier?: ConcertTier } = {}): Concert[] {
  return CONCERTS.filter((concert) => isCurrent(concert))
    .filter((concert) => !options.ciudad || concert.city === options.ciudad)
    .filter((concert) => !options.tier || concert.tier === options.tier)
    .slice()
    .sort((a, b) => a.start.localeCompare(b.start) || a.artist.localeCompare(b.artist, 'es'))
}

export function concertById(id: string): Concert | undefined {
  const concert = CONCERTS.find((item) => item.id === id)
  return concert && isCurrent(concert) ? concert : undefined
}

export function concertCities(): string[] {
  return [...new Set(CONCERTS.map((concert) => concert.city))].sort((a, b) => a.localeCompare(b, 'es'))
}

const MONTHS = ['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto', 'septiembre', 'octubre', 'noviembre', 'diciembre']

export function monthLabel(isoDate: string): string {
  const [year, month] = isoDate.split('-')
  return `${MONTHS[Number(month) - 1]} de ${year}`
}

export function groupByMonth(concerts: Concert[]): { label: string; items: Concert[] }[] {
  const groups = new Map<string, Concert[]>()
  for (const concert of concerts) {
    const key = concert.start.slice(0, 7)
    const list = groups.get(key) ?? []
    list.push(concert)
    groups.set(key, list)
  }
  return [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, items]) => ({ label: monthLabel(`${key}-01`), items }))
}
